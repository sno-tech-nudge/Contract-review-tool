import { notFound } from "next/navigation";
import { prisma } from "@/lib/db";
import { contractTypeLabel } from "@/lib/contracts/types";
import { riskBand, type CheckKind, type ReviewResult } from "@/lib/review/types";
import { PrintButton } from "@/components/review/PrintButton";
import { SeverityBadge, StatusIcon, formatDate } from "@/components/ui";

export const dynamic = "force-dynamic";

const SECTIONS: { key: CheckKind; title: string }[] = [
  { key: "boilerplate", title: "Boilerplate" },
  { key: "legal", title: "Legal" },
  { key: "business", title: "Business rules" },
  { key: "ai", title: "Additional risks (AI)" },
];

// A clean, printable summary of a review: save as PDF from the browser.
export default async function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const review = await prisma.review.findUnique({ where: { id }, include: { document: true } });
  if (!review) notFound();
  const result = JSON.parse(review.resultJson) as ReviewResult;
  const band = riskBand(review.riskScore);
  const open = result.findings.filter((f) => f.status !== "pass");

  return (
    <main className="report">
      <div className="no-print" style={{ display: "flex", justifyContent: "flex-end", marginBottom: "var(--space-5)" }}>
        <PrintButton />
      </div>
      <img src="/brand/thenudge-wordmark-brown.png" alt="The/Nudge" style={{ height: 18, marginBottom: "var(--space-5)" }} />
      <span className="kicker">Contract review report</span>
      <h1>{review.document.title}</h1>
      <p className="muted" style={{ fontSize: "var(--text-sm)" }}>
        {contractTypeLabel(result.contractType)} · {review.document.pageCount} pages · reviewed {formatDate(review.createdAt)}
      </p>

      <div className="risk" style={{ margin: "var(--space-5) 0" }}>
        <div className="risk__score">
          {review.riskScore}
          <small>/100</small>
        </div>
        <div>
          <span className={`badge badge--${band.tone}`}>{band.label}</span>
          <div className="risk__counts" style={{ marginTop: "var(--space-2)" }}>
            <span>
              <b>{result.findings.filter((f) => f.status === "issue").length}</b> issues
            </span>
            <span>
              <b>{result.findings.filter((f) => f.status === "warning").length}</b> to check
            </span>
            <span>
              <b>{result.findings.filter((f) => f.status === "pass").length}</b> passed
            </span>
          </div>
        </div>
      </div>

      <h2>Summary</h2>
      <p style={{ fontSize: "var(--text-sm)", maxWidth: "none" }}>{result.summary}</p>
      {result.keyTerms.length > 0 && (
        <div className="terms" style={{ marginTop: "var(--space-4)" }}>
          {result.keyTerms.map((k, i) => (
            <div className="term" key={i}>
              <div className="term__label">{k.label}</div>
              <div className="term__value">{k.value}</div>
            </div>
          ))}
        </div>
      )}

      {SECTIONS.map(({ key, title }) => {
        const fs = open.filter((f) => f.check === key);
        if (!fs.length) return null;
        return (
          <section key={key}>
            <h2>
              {title} <span className="faint num">({fs.length})</span>
            </h2>
            {fs.map((f) => (
              <div className="r-finding" key={f.id}>
                <h4>
                  <StatusIcon status={f.status} className="finding__icon" /> {f.title} <SeverityBadge severity={f.severity} />
                  {f.page ? <span className="micro">p.{f.page}</span> : null}
                </h4>
                <p>{f.detail}</p>
                {f.quote && <p className="r-quote">“{f.quote}”</p>}
                {f.recommendation && (
                  <p>
                    <b style={{ fontWeight: 500 }}>Recommendation:</b> {f.recommendation}
                  </p>
                )}
                {f.reference && <p className="finding__ref">{f.reference}</p>}
              </div>
            ))}
          </section>
        );
      })}

      <p className="disclaimer">
        Generated by The/Nudge contract review tool. Automated checks flag points to confirm and are not legal advice. Passed checks are omitted from this report.
      </p>
    </main>
  );
}
